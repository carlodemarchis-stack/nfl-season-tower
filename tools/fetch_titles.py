#!/usr/bin/env python3
"""Super Bowl rings and Super Bowl MVPs for every player on a 2026 roster.

    python3 tools/fetch_titles.py 2025      # last completed season

ESPN has no "champion" award, so a ring is read from the game itself: for each Super
Bowl, the winning side's game roster, keeping only players who actually played
(didNotPlay is false). The Super Bowl MVP is ESPN's award 317 for that season.
Run once a year, after the Super Bowl -- nothing here changes in between.
"""
import json, os, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://site.api.espn.com/apis/site/v2/sports/football/nfl"
CORE = "https://sports.core.api.espn.com/v2/sports/football/leagues/nfl"
ALIAS = {"WSH": "WAS", "LA": "LAR", "JAC": "JAX"}
FIRST = 2000


def get(url):
    # curl, not urllib: ESPN 403s Python's default client
    out = subprocess.run(["curl", "-s", "--compressed", "--max-time", "40", url], capture_output=True, text=True).stdout
    try:
        return json.loads(out)
    except ValueError:
        return {}


def roman(n):
    out = ""
    for v, s in ((50, "L"), (40, "XL"), (10, "X"), (9, "IX"), (5, "V"), (4, "IV"), (1, "I")):
        while n >= v:
            out += s
            n -= v
    return out


def season(y):
    # The Super Bowl is postseason week 5 since 2009 (the Pro Bowl moved before it) and
    # week 4 until then; skip the Pro Bowl itself (AFC v NFC).
    ev = None
    for wk in (5, 4):
        evs = [e for e in get(f"{SITE}/scoreboard?dates={y}&seasontype=3&week={wk}").get("events") or []
               if not {"AFC", "NFC"} & {c["team"]["abbreviation"] for c in e["competitions"][0]["competitors"]}]
        if evs:
            ev = evs[-1]
            break
    if not ev:
        return None
    c = ev["competitions"][0]
    win = next((x for x in c["competitors"] if x.get("winner")), None)
    lose = next((x for x in c["competitors"] if not x.get("winner")), None)
    if not win:
        return None
    ros = get(f"{CORE}/events/{ev['id']}/competitions/{ev['id']}/competitors/{win['team']['id']}/roster?limit=200")
    played = [str(e["playerId"]) for e in ros.get("entries", []) if not e.get("didNotPlay")]
    mvp = get(f"{CORE}/seasons/{y}/awards/317")
    mvps = [w["athlete"]["$ref"].split("/athletes/")[1].split("?")[0]
            for w in mvp.get("winners", []) if w.get("athlete")]
    ab = lambda t: ALIAS.get(t["team"]["abbreviation"], t["team"]["abbreviation"])
    return {"y": y, "sb": roman(y - 1965), "win": ab(win), "lose": ab(lose),
            "score": f"{win['score']}-{lose['score']}", "played": played, "mvp": mvps}


def main(last):
    with ThreadPoolExecutor(max_workers=6) as ex:
        games = [g for g in ex.map(season, range(FIRST, last + 1)) if g]
    ids = set()
    for p in ("rosters-2026.js",):
        s = open(os.path.join(ROOT, "src/data", p)).read()
        r = json.JSONDecoder().raw_decode(s[s.index("{", s.index("ROSTERS2026")):])[0]
        ids |= {x["id"] for t in r.values() for x in t["players"]}
    rings, mvp = {}, {}
    for g in games:
        for pid in g["played"]:
            if pid in ids:
                rings.setdefault(pid, []).append(g["y"])
        for pid in g["mvp"]:
            if pid in ids:
                mvp.setdefault(pid, []).append(g["y"])
    if len(games) < last - FIRST:
        print(f"only {len(games)} Super Bowls found — not writing", file=sys.stderr)
        sys.exit(1)
    sbs = {g["y"]: {k: g[k] for k in ("sb", "win", "lose", "score")} for g in games}
    out = {"through": last, "sb": sbs, "rings": rings, "mvp": mvp}
    p = os.path.join(ROOT, "src/data/titles.js")
    with open(p, "w") as f:
        f.write("// Super Bowl rings (played in the game for the winner) and Super Bowl MVPs for\n"
                "// players on a 2026 roster. Generated by tools/fetch_titles.py from ESPN.\n")
        f.write("export const TITLES = " + json.dumps(out, separators=(",", ":")) + "\n")
    print(f"{len(games)} Super Bowls, {len(rings)} current players with a ring, "
          f"{len(mvp)} with a Super Bowl MVP -> {os.path.relpath(p, ROOT)}")
    for y in sorted(sbs)[-4:]:
        print(f"  {y}: SB {sbs[y]['sb']} {sbs[y]['win']} {sbs[y]['score']} {sbs[y]['lose']}")


main(int(sys.argv[1]) if len(sys.argv) > 1 else 2025)
