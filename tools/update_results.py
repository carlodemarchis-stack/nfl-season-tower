#!/usr/bin/env python3
"""Refresh src/data/results-2026.js from ESPN's public scoreboard.

Only FINAL games are written; anything scheduled/in-progress stays absent, which is
exactly what the tower renders as "upcoming". Every game is validated against
schedule-2026.js (team, week and opponent must match) before it is accepted, so a
bad pull fails loudly instead of silently corrupting the board.

  python3 tools/update_results.py            # write
  python3 tools/update_results.py --dry-run  # report only
"""
import json, re, subprocess, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHED = os.path.join(ROOT, 'src/data/schedule-2026.js')
OUT   = os.path.join(ROOT, 'src/data/results-2026.js')
SEASON, WEEKS = 2026, 18

# ESPN abbreviation -> our schedule key
ALIAS = {'WSH': 'WAS', 'LA': 'LAR', 'JAC': 'JAX'}
norm = lambda a: ALIAS.get(a, a)

def fetch(week):
    url = (f'https://site.api.espn.com/apis/site/v2/sports/football/nfl/scoreboard'
           f'?dates={SEASON}&seasontype=2&week={week}')
    out = subprocess.run(['curl', '-s', '--max-time', '30', url],
                         capture_output=True, text=True).stdout
    return json.loads(out) if out.strip() else {}

def main():
    dry = '--dry-run' in sys.argv
    src = open(SCHED).read()
    TEAMS, _ = json.JSONDecoder().raw_decode(src[src.index('{'):])
    # (team, week) -> opponent, straight from the shipped fixture list
    fixture = {(ab, g['w']): g['opp'] for ab, t in TEAMS.items() for g in t['games']}

    results, finals, problems = {}, 0, []
    for wk in range(1, WEEKS + 1):
        data = fetch(wk)
        for e in data.get('events', []):
            comp = e['competitions'][0]
            if comp['status']['type'].get('name') != 'STATUS_FINAL':
                continue
            cs = comp['competitors']
            if len(cs) != 2:
                continue
            (a, sa), (b, sb) = [(norm(c['team']['abbreviation']), int(c.get('score') or 0)) for c in cs]
            # validate both directions against the fixture list
            for x, y in ((a, b), (b, a)):
                if fixture.get((x, wk)) != y:
                    problems.append(f'wk{wk} {x} vs {y}: fixture says {fixture.get((x, wk))!r}')
            res = lambda u, t: 'W' if u > t else ('L' if u < t else 'T')
            results[f'{a}:{wk}'] = {'us': sa, 'them': sb, 'res': res(sa, sb), 'hasU': True, 'hasT': True}
            results[f'{b}:{wk}'] = {'us': sb, 'them': sa, 'res': res(sb, sa), 'hasU': True, 'hasT': True}
            finals += 1
        print(f'  week {wk:2}: {finals} finals so far', flush=True)

    if problems:
        print('\nVALIDATION FAILED — not writing:', file=sys.stderr)
        for p in problems[:20]:
            print('  ' + p, file=sys.stderr)
        sys.exit(1)

    played = sorted({int(k.split(':')[1]) for k in results})
    print(f'\n{finals} final games ({len(results)} rows); weeks with results: {played or "none"}')
    for k in sorted(results, key=lambda k: (int(k.split(":")[1]), k))[:8]:
        r = results[k]
        print(f'  {k:8} {r["res"]} {r["us"]}-{r["them"]}')
    if dry:
        print('\n--dry-run: nothing written'); return

    body = json.dumps(results, separators=(',', ':'), sort_keys=True)
    open(OUT, 'w').write(
        '// Real 2026 regular-season results, keyed "ABBR:week" (both sides of each game).\n'
        '// Generated by tools/update_results.py from ESPN — FINAL games only; anything not\n'
        '// present renders as an upcoming game (hangs from the ceiling in the tower).\n'
        f'export const RESULTS2026 = {body}\n'
        'export const MAXWEEK2026 = 18\n')
    print(f'\nwrote {OUT}')

main()
